import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir,writeFile } from "node:fs/promises";
import { resolve,join } from "node:path";
const [base,output,modulePath,executablePath]=process.argv.slice(2);
const { chromium }=createRequire(import.meta.url)(resolve(modulePath));
const browser=await chromium.launch({executablePath,args:["--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
await mkdir(output,{recursive:true});
const checks=[];
const check=(value,label)=>{assert.ok(value,label);checks.push(label);};
try {
  const page=await browser.newPage();
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.addInitScript(()=>{
    window.pad={index:0,connected:true,mapping:"standard",axes:[0,0,0,0],
      buttons:Array.from({length:17},()=>({pressed:false,value:0}))};
    Object.defineProperty(navigator,"getGamepads",{value:()=>[window.pad]});
  });
  await page.goto(base);
  const view=()=>page.evaluate(()=>window.movementReview.inspect());
  await page.waitForFunction(()=>window.movementReview?.inspect().ready);
  const canvas=page.locator("#screen");
  const pixels=()=>canvas.evaluate(x=>x.toDataURL());
  const neutral=await pixels();
  const protectedPixels=()=>page.evaluate(()=>{
    const c=document.querySelector("#screen"), gl=c.getContext("webgl");
    const bytes=new Uint8Array(101*43*4);
    gl.readPixels(18,c.height-59,101,43,gl.RGBA,gl.UNSIGNED_BYTE,bytes);
    return Array.from(bytes);
  });
  const protectedBefore=await protectedPixels();
  check((await view()).render.height===480,"Candidate renders at the fixture height");
  check((await view()).render.frame===0,"Initial pose starts at the first source frame");
  check(await page.locator("#part option").count()===6,"All independently controllable groups are available");
  check((await page.request.get(new URL("missing.mp4",base).href)).status()===404,"Missing media returns a clear failure status");
  const axis=(i,v)=>page.evaluate(([i,v])=>window.pad.axes[i]=v,[i,v]);
  const button=(i,v)=>page.evaluate(([i,v])=>{window.pad.buttons[i]={value:v,pressed:!!v};},[i,v]);
  const seek=async index=>{
    await page.locator("#time").evaluate((el,n)=>{el.value=n;el.dispatchEvent(new Event("input"));},index);
    await page.waitForFunction(i=>window.movementReview.inspect().render.frame===i,index);
  };
  await page.waitForFunction(()=>window.movementReview.inspect().padIndex===0);
  check((await view()).render.width===480,"Opening keeps native width");
  const r=await page.request.get(new URL("video.mp4",base).href,{headers:{Range:"bytes=0-15"}});
  check(r.status()===206&&(await r.body()).length===16,"Range media delivery");
  await axis(0,.05);
  await page.evaluate(()=>new Promise(requestAnimationFrame));
  check((await view()).motion.root.every(x=>x===0),"Neutral stick noise is ignored");
  await axis(0,-.9);
  await page.waitForFunction(()=>window.movementReview.inspect().motion.root[0]<-40);
  await axis(0,0);
  check((await view()).paused&&(await view()).position===0,"Travel is independent of playback");
  check(await pixels()!==neutral,"Travel changes rendered pixels");
  check((await protectedPixels()).every((x,i)=>x===protectedBefore[i]),"Protected graphic remains pixel exact");
  await axis(2,.95);
  await page.waitForFunction(()=>window.movementReview.inspect().motion.offsets[0][0]>.19);
  await axis(2,0);
  check((await view()).render.subjects[0][15].every(Number.isFinite),"Independent arm motion reaches renderer");
  await button(0,1);
  await page.waitForFunction(()=>window.movementReview.inspect().motion.lift>14);
  await button(0,0);
  check(true,"Jump works during combined control");
  await seek(17);
  check((await view()).render.width===544,"Active pose carries into widened frame");
  check((await view()).motion.offsets[0][0]>.19,"Joint setting persists across the wider cut");
  await seek(35);
  check((await view()).render.width===480&&(await view()).render.subjects.length===2,"Narrow cut renders reflected layer");
  check((await view()).render.subjects[1][23].every(Number.isFinite),"Reflected pose uses evaluated joints");
  await canvas.screenshot({path:join(output,"reflected-pose.png")});
  await seek(0);
  await button(1,1);
  await page.waitForFunction(()=>window.movementReview.inspect().render.subjects.length===0);
  await button(1,0);
  check(await pixels()===neutral,"Reset restores exact rendered source pixels");
  await page.evaluate(()=>window.pad.connected=false);
  await page.waitForFunction(()=>window.movementReview.inspect().padIndex===null);
  check((await page.locator("#pad").textContent()).includes("disconnected"),"Disconnect is reported");
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"Controls fit a narrow viewport");
  check(errors.length===0,"No browser script errors");
  await writeFile(join(output,"results.json"),JSON.stringify({checks},null,2)+"\n");
} finally { await browser.close(); }
