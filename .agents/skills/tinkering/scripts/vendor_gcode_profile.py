#!/usr/bin/env python3
"""Summarise - and diff - the first-layer settings of sliced G-code files.

Use this on the vendor demo files that ship on a printer's SD card. Those were tuned for that exact
machine, so when one of them prints cleanly on a bed where your own prints fail, the difference is in the
settings and this reads them out. Diffing several vendor files tells you which values are the profile
(identical everywhere) and which are per-model choices.

Recognises Simplify3D 'Settings Summary' comment blocks and PrusaSlicer/Slic3r trailing 'key = value'
comment blocks, and falls back to reading the actual machine commands (M104/M109/M140/M190/M106) and the
first commanded Z, which is the only reliable way to see the true first-layer height when the profile
expresses it as a percentage.

Usage:
    vendor_gcode_profile.py dog.gcode                 # one summary
    vendor_gcode_profile.py dog.gcode cat.gcode pig.gcode --diff
    vendor_gcode_profile.py *.gcode --json profiles.json
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# Settings worth reading when deciding why a print sticks. Keys are matched case-insensitively against
# both slicer dialects; the list is deliberately short so the output stays readable.
KEYS_OF_INTEREST = (
    'layerheight', 'layer_height', 'firstlayerheightpercentage', 'first_layer_height',
    'firstlayerwidthpercentage', 'firstlayerunderspeed', 'first_layer_speed',
    'useraft', 'raft_layers', 'raftbaselayers', 'rafttoplayers', 'raftoffset', 'raft_expansion',
    'raftseparationdistance', 'raft_contact_distance', 'raft_first_layer_expansion',
    'useskirt', 'skirts', 'brim_width', 'skirtoffset',
    'temperaturesetpointtemperatures', 'temperature', 'first_layer_temperature',
    'bed_temperature', 'first_layer_bed_temperature',
    'fanlayers', 'fanspeeds', 'min_fan_speed', 'max_fan_speed', 'disable_fan_first_layers',
    'defaultspeed', 'perimeteroutlines', 'perimeters', 'infillpercentage', 'fill_density',
    'generatesupport', 'support_material', 'extruderdiameter', 'nozzle_diameter',
)
S3D_RE = re.compile(r'^;\s{2,}([A-Za-z_][A-Za-z0-9_]*),(.*)$')
PRUSA_RE = re.compile(r'^;\s*([a-z0-9_]+)\s*=\s*(.*)$')
CMD_RE = re.compile(r'^(M104|M109|M140|M190|M106|M107)\b(?:.*?S(-?\d+(?:\.\d+)?))?')
Z_RE = re.compile(r'^G[01](?=[ \t]).*?[Zz](-?\d+(?:\.\d+)?)')
E_RE = re.compile(r'[Ee](-?\d+(?:\.\d+)?)')


def read_profile(path: Path) -> dict:
    settings: dict[str, str] = {}
    commands: list[str] = []
    first_extruding_z = None
    last_z = None
    generator = ''
    with path.open('r', errors='replace') as fh:
        for line in fh:
            line = line.rstrip('\n')
            if line.startswith(';'):
                if not generator and ('generated by' in line.lower() or 'prusaslicer' in line.lower()):
                    generator = line.lstrip('; ').strip()
                m = S3D_RE.match(line) or PRUSA_RE.match(line)
                if m and m.group(1).lower() in KEYS_OF_INTEREST:
                    settings.setdefault(m.group(1), m.group(2).strip())
                continue
            m = CMD_RE.match(line)
            if m and len(commands) < 12:
                commands.append(line.split(';')[0].strip())
            # Slicers usually raise Z on its own line and extrude on the following X/Y lines, so the
            # first-layer height is the LAST commanded Z at the moment of the first extruding move -
            # not the Z of a line that happens to carry both.
            mz = Z_RE.match(line)
            if mz:
                last_z = float(mz.group(1))
            if first_extruding_z is None and last_z is not None:
                me = E_RE.search(line)
                if me and float(me.group(1)) > 0:
                    first_extruding_z = last_z
    return dict(file=path.name, generator=generator, first_extruding_z=first_extruding_z,
                startup_commands=commands, settings=settings)


def print_profile(p: dict) -> None:
    print(f"=== {p['file']} ===")
    if p['generator']:
        print(f"  {p['generator']}")
    print(f"  first extruding Z : {p['first_extruding_z']}   <- the real first-layer height")
    if p['startup_commands']:
        print(f"  startup           : {' | '.join(p['startup_commands'][:8])}")
    for k, v in sorted(p['settings'].items()):
        print(f"  {k:<34} {v}")
    print()


def diff(profiles: list[dict]) -> int:
    """Print which settings are shared by every file and which differ. Returns the count that differ."""
    keys: set[str] = set()
    for p in profiles:
        keys |= set(p['settings'])
    same, differ = {}, {}
    for k in sorted(keys):
        vals = {p['file']: p['settings'].get(k, '<absent>') for p in profiles}
        if len(set(vals.values())) == 1:
            same[k] = next(iter(vals.values()))
        else:
            differ[k] = vals
    print(f"=== shared by all {len(profiles)} files (this is the machine profile) ===")
    for k, v in same.items():
        print(f"  {k:<34} {v}")
    print(f"\n=== differs between files (per-model choices, not the profile) ===")
    if not differ:
        print('  (nothing)')
    for k, vals in differ.items():
        print(f"  {k}")
        for f, v in vals.items():
            print(f"      {f:<22} {v}")
    zs = {p['file']: p['first_extruding_z'] for p in profiles}
    print(f"\n  first extruding Z: {zs}")
    return len(differ)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('files', nargs='+', type=Path)
    ap.add_argument('--diff', action='store_true', help='compare the files instead of listing each in full')
    ap.add_argument('--json', type=Path, help='write the parsed profiles here')
    args = ap.parse_args(argv)

    profiles = [read_profile(p) for p in args.files]
    if args.diff and len(profiles) > 1:
        diff(profiles)
    else:
        for p in profiles:
            print_profile(p)
    if args.json:
        args.json.write_text(json.dumps(profiles, indent=1))
        print(f'report: {args.json}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
