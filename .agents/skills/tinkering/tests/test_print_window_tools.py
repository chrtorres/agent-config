"""Behavioural tests for check_print_window.py and vendor_gcode_profile.py.

All fixtures are synthetic G-code written at test time - no printer, no vendor file and no path from any
particular machine is required. Run from anywhere:

    python3 -m unittest discover -s <skill>/tests -v
"""
from __future__ import annotations

import importlib.util
import io
import json
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent.parent / 'scripts'


def load(name: str):
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f'{name}.py')
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


cpw = load('check_print_window')
vgp = load('vendor_gcode_profile')


def synthetic_gcode(x0: float, x1: float, y0: float, y1: float,
                    prime_x: float = 5.0, prime_y0: float = 5.0, prime_y1: float = 200.0) -> str:
    """A start block that primes at the bed edge, then a square of extruding moves well inside it."""
    return '\n'.join([
        '; generated by SyntheticSlicer 1.0',
        ';TYPE:Custom',
        'G28',
        f'G1 X{prime_x} Y{prime_y0} Z0.3 F5000',
        f'G1 X{prime_x} Y{prime_y1} Z0.3 E15 F1500',
        ';TYPE:Skirt',
        f'G1 X{x0} Y{y0} Z0.3 F5000',
        f'G1 X{x1} Y{y0} E1.0',
        f'G1 X{x1} Y{y1} E1.0',
        f'G1 X{x0} Y{y1} E1.0',
        f'G1 X{x0} Y{y0} E1.0',
        '; estimated printing time (normal mode) = 1h 2m 3s',
        '; total filament used [g] = 12.5',
        '',
    ])


class CheckPrintWindowTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, name: str, text: str) -> Path:
        p = self.dir / name
        p.write_text(text)
        return p

    def test_prime_lines_are_excluded_by_default(self):
        """The edge prime line must not drag the measured minimum out to the bed edge."""
        p = self.write('a.gcode', synthetic_gcode(40, 120, 40, 120, prime_x=5))
        row = cpw.measure(p)
        self.assertTrue(row['measured'])
        self.assertEqual(row['x'], [40.0, 120.0])
        self.assertEqual(row['y'], [40.0, 120.0])

    def test_include_start_sees_the_prime_line(self):
        p = self.write('a.gcode', synthetic_gcode(40, 120, 40, 120, prime_x=5))
        row = cpw.measure(p, include_start=True)
        self.assertEqual(row['x'][0], 5.0)

    def test_travel_moves_do_not_count(self):
        """A non-extruding move outside the window is legal and must not be reported."""
        body = synthetic_gcode(40, 120, 40, 120) + 'G1 X210 Y210 F9000\n'
        p = self.write('a.gcode', body)
        self.assertEqual(cpw.measure(p)['x'][1], 120.0)

    def test_axis_omitted_from_a_move_uses_the_last_position(self):
        text = '\n'.join([';TYPE:Perimeter', 'G1 X50 Y50 E1', 'G1 X90 E1', 'G1 Y95 E1', ''])
        p = self.write('a.gcode', text)
        row = cpw.measure(p)
        self.assertEqual(row['x'], [50.0, 90.0])
        self.assertEqual(row['y'], [50.0, 95.0])

    def test_in_window_passes_and_out_of_window_fails(self):
        good = self.write('good.gcode', synthetic_gcode(40, 120, 40, 120))
        bad = self.write('bad.gcode', synthetic_gcode(20, 160, 40, 120))
        with redirect_stdout(io.StringIO()):
            rc_good = cpw.main(['--window', '30,147,30,160', str(good)])
            rc_bad = cpw.main(['--window', '30,147,30,160', str(bad)])
        self.assertEqual(rc_good, 0)
        self.assertEqual(rc_bad, 1)

    def test_margin_tightens_the_check(self):
        p = self.write('edge.gcode', synthetic_gcode(31, 146, 40, 120))
        with redirect_stdout(io.StringIO()):
            self.assertEqual(cpw.main(['--window', '30,147,30,160', str(p)]), 0)
            self.assertEqual(cpw.main(['--window', '30,147,30,160', '--margin', '3', str(p)]), 1)

    def test_time_and_weight_are_reported(self):
        p = self.write('a.gcode', synthetic_gcode(40, 120, 40, 120))
        row = cpw.measure(p)
        self.assertEqual(row['time'], '1h 2m 3s')
        self.assertEqual(row['grams'], 12.5)

    def test_file_without_extrusions_is_reported_not_crashed(self):
        p = self.write('empty.gcode', ';TYPE:Custom\nG28\n')
        row = cpw.measure(p)
        self.assertFalse(row['measured'])
        with redirect_stdout(io.StringIO()):
            self.assertEqual(cpw.main(['--window', '30,147,30,160', str(p)]), 1)

    def test_json_report_round_trips(self):
        p = self.write('a.gcode', synthetic_gcode(40, 120, 40, 120))
        out = self.dir / 'r.json'
        with redirect_stdout(io.StringIO()):
            cpw.main(['--window', '30,147,30,160', '--json', str(out), str(p)])
        data = json.loads(out.read_text())
        self.assertEqual(data['window'], [30.0, 147.0, 30.0, 160.0])
        self.assertTrue(data['files'][0]['ok'])


class VendorProfileTests(unittest.TestCase):
    S3D = '\n'.join([
        '; G-Code generated by SyntheticSlicer(R) Version 4.0.1',
        '; Settings Summary',
        ';   layerHeight,0.1',
        ';   firstLayerHeightPercentage,90',
        ';   useRaft,1',
        ';   raftBaseLayers,2',
        ';   raftTopLayers,3',
        ';   raftSeparationDistance,0.14',
        ';   raftOffset,3',
        ';   temperatureSetpointTemperatures,200,45',
        ';   fanLayers,1,2',
        ';   fanSpeeds,0,100',
        ';   generateSupport,{support}',
        ';   Build time: {time}',
        'M140 S45',
        'M190 S45',
        'M104 S200 T0',
        'M109 S200 T0',
        'G28 ; home',
        'G1 Z0.750 F1002',
        'G1 Z0.450 F1002',
        'G1 X50 Y50 Z0.450 E1.0',
        '',
    ])

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, name: str, support: str, time: str) -> Path:
        p = self.dir / name
        p.write_text(self.S3D.format(support=support, time=time))
        return p

    def test_reads_settings_and_the_real_first_layer_height(self):
        p = self.write('dog.gcode', '0', '2 hours')
        prof = vgp.read_profile(p)
        self.assertEqual(prof['settings']['temperatureSetpointTemperatures'], '200,45')
        self.assertEqual(prof['settings']['raftOffset'], '3')
        # The profile says 0.1 * 90%, but the machine is actually told to print the raft at 0.45.
        self.assertEqual(prof['first_extruding_z'], 0.45)

    def test_startup_commands_are_captured(self):
        prof = vgp.read_profile(self.write('dog.gcode', '0', '2 hours'))
        self.assertIn('M190 S45', prof['startup_commands'])
        self.assertIn('M109 S200 T0', prof['startup_commands'])

    def test_diff_separates_shared_profile_from_per_model_settings(self):
        a = vgp.read_profile(self.write('dog.gcode', '0', '2 hours'))
        b = vgp.read_profile(self.write('cat.gcode', '0', '3 hours'))
        c = vgp.read_profile(self.write('pig.gcode', '1', '4 hours'))
        buf = io.StringIO()
        with redirect_stdout(buf):
            n_differ = vgp.diff([a, b, c])
        text = buf.getvalue()
        self.assertEqual(n_differ, 1)                       # only generateSupport differs
        self.assertIn('generateSupport', text.split('differs between files')[1])
        self.assertIn('temperatureSetpointTemperatures', text.split('differs between files')[0])

    def test_first_layer_z_is_found_when_z_is_on_its_own_line(self):
        """Slicers raise Z on a separate line and extrude afterwards; the tool must still report 0.45."""
        p = self.dir / 'sep.gcode'
        p.write_text('\n'.join(['G28', 'G1 Z0.750 F1002', 'G1 Z0.450 F1002',
                                'G1 X10 Y10 F5000', 'G1 X60 Y10 E2.5', 'G1 Z12.0', 'G1 X60 Y60 E2.5', '']))
        self.assertEqual(vgp.read_profile(p)['first_extruding_z'], 0.45)

    def test_retraction_is_not_mistaken_for_an_extruding_move(self):
        p = self.dir / 'ret.gcode'
        p.write_text('\n'.join(['G1 Z0.300', 'G1 E-5.0 F2700', 'G1 Z0.450', 'G1 X10 Y10 E1.0', '']))
        self.assertEqual(vgp.read_profile(p)['first_extruding_z'], 0.45)

    def test_prusa_style_comments_are_parsed(self):
        p = self.dir / 'p.gcode'
        p.write_text('G1 X1 Y1 Z0.4 E1\n; first_layer_temperature = 200\n; raft_layers = 5\n')
        prof = vgp.read_profile(p)
        self.assertEqual(prof['settings']['first_layer_temperature'], '200')
        self.assertEqual(prof['settings']['raft_layers'], '5')


if __name__ == '__main__':
    unittest.main()
